  function fire(kind, opts) {
    if (!isOn()) return false;
    kind = resolveKind(kind);
    var a = api();
    if (!a || !a.talkStreamStart) return false;
    holdLane(function () { fireNow(kind, opts); });
    return true;
  }
  function fireNow(kind, opts) {
    if (!isOn()) { releaseLane(); return; }
    var a = api();
    if (!a || !a.talkStreamStart) { releaseLane(); return; }
    var nm = userName();
    var vars = varsFor(kind);
    var fallback = fb(kind, vars);
    // 🧠 W-FEAT193 (I122) — build the prompt while the pending feature is still known, then record the pick
    // (so the same feature is never named twice and the 3-4h window restarts) and clear it. This happens
    // before the generateText fallback path too, so a feature tip that only shows its template is still
    // remembered. NOTE: featNote() writes ONLY into LS_TIPS — nothing the visitor chose is ever erased.
    var _promptStr = "";
    try { _promptStr = buildPrompt(kind); } catch (e) {}
    if (kind === "featuretip" && _pendingFeature) { featNote(_pendingFeature.key); _pendingFeature = null; }
    lsSet(LS_LAST, String(Date.now()));
    var ms = (opts && opts.ms) || BUBBLE_MS;
    var g = null;
    try { g = window.root && window.root.generateText; } catch (e) {}
    if (typeof g !== "function") { try { a.talk(fallback, ms); } catch (e) {} return true; }
    var acc = "";
    var settled = false;
    var obj = null;
    var guardFast = null, guardHard = null;
    function finish(text) {
      if (settled) return;
      settled = true;
      if (text !== fallback) { try { text = scrubNumbers(text, kind); } catch (e) {} }
      if (guardFast) { clearTimeout(guardFast); guardFast = null; }
      if (guardHard) { clearTimeout(guardHard); guardHard = null; }
      try { a.talkStreamEnd(text, ms); } catch (e) {}
    }
    try {
      a.talkStreamStart();
      obj = window.root.generateText({
        instruction: _promptStr,
        onChunk: function (d) {
          if (settled) return;
          if (d && d.textChunk) { acc += d.textChunk; try { a.talkStreamChunk(acc); } catch (e) {} }
        }
      });
      // Egon 18.09.2026 — FAST FALLBACK: if not a single token arrives in time the bubble would sit on the
      // animated "writing" dots forever — abort and show the localized template instead. A second, longer
      // guard makes sure the bubble always ends (and therefore auto-hides) even if the stream dies mid-reply.
      guardFast = setTimeout(function () {
        if (settled || acc) return;
        try { if (obj && obj.stop) obj.stop(); } catch (e) {}
        finish(fallback);
      }, (opts && opts.timeoutMs) || FAST_FALLBACK_MS);
      guardHard = setTimeout(function () { finish(clean(acc) || fallback); }, HARD_FALLBACK_MS);
      Promise.resolve(obj).then(function (fin) {
        if (settled) return;
        try { if (fin && typeof fin === "object" && fin.text) acc = fin.text; else if (typeof fin === "string" && fin) acc = fin; } catch (e) {}
        finish(clean(acc) || fallback);
      }).catch(function () { finish(fallback); });
    } catch (e) {
      finish(fallback);
    }
    // the lane is held while the bubble is on screen: give it back once the bubble has finished showing
    // (the text is typed out character by character first, so the read-time countdown starts later than
    // `ms` would suggest — add a small allowance on top).
    try { setTimeout(releaseLane, Math.max(6000, ms + 4000)); } catch (e) {}
    return true;
  }

