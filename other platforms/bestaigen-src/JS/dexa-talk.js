  function clean(txt) {
    return String(txt || "")
      .replace(/```[\s\S]*?```/g, " ")
      .replace(/^[\s"'“”«»]+|[\s"'“”«»]+$/g, "")
      // Hard OUTPUT guard: no matter what the model returned, a Dexa bubble can never carry a leaked
      // placeholder "name" or the name of another companion.
      .replace(/[\s,]*\b(?:undefined|null|nan)\b/gi, "")
      .replace(/\bsexa\b/gi, "Dexa")
      .replace(/\s+/g, " ")
      .trim()
      .slice(0, 200);
  }

  // Egon 29.09.2026 — the model sometimes INVENTS its own online count instead of the real
  // number from the prompt. Deterministic guard: an online/milestone bubble may only carry the REAL
  // count — any other standalone number in the AI text is swapped for it before showing.
  function scrubNumbers(txt, kind) {
    var N = 0;
    if (kind === "online") { try { N = onlineCount() - 1; } catch (e) { N = 0; } }
    else if (kind === "milestone" || kind === "milestoneBig") N = milestoneN;
    if (!(N >= 1)) return txt;
    return String(txt).replace(/\d[\d.,]*/g, function (m) {
      var v = parseInt(String(m).replace(/[.,]/g, ""), 10);
      return (v === N) ? m : String(N);
    });
  }

