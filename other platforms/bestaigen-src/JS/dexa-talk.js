      if (nextAt && now >= nextAt) {
        if (busy() || !isOn()) { nextAt = now + RETRY_MIN * 60000; return; }
        if (fire()) { ssSet(SS_COUNT, String(count() + 1)); scheduleNext(); }
        else { nextAt = now + RETRY_MIN * 60000; }
        return;
      }
