  var _laneHeld = false;
  function holdLane(run) {
    var lane = null;
    try { lane = window.dragonMarquee; } catch (e) {}
    if (!lane || typeof lane.request !== "function") { try { run(); } catch (e) {} return; }
    lane.request(function () { _laneHeld = true; try { run(); } catch (e) { releaseLane(); } });
  }
